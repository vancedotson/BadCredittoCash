-- CRM payment requests collected through Authorize.net Accept Hosted.
-- Additive except for the listed CREATE OR REPLACE / constraint changes. The
-- application keeps the feature inert unless PAYMENTS_ENABLED=true and all
-- Authorize.net credentials are configured. Card data never reaches this
-- database: only the processor's transaction id, status, card brand and last
-- four digits are stored. Authorize.net remains the financial system of record.

create table public.payment_requests (
  id uuid primary key default gen_random_uuid(),
  -- No contacts FK: recoverable trash temporarily removes the contact row while
  -- keeping its payment history; the guard trigger below requires an active
  -- contact for new or re-pointed rows.
  contact_id uuid not null,
  -- Human reference and Authorize.net invoiceNumber (max 20 characters).
  reference text not null unique check (reference ~ '^CRP-[2-9A-HJKMNP-Z]{8}$'),
  link_token text not null unique check (link_token ~ '^[A-Za-z0-9_-]{43}$'),
  amount_cents integer not null check (amount_cents between 100 and 2500000),
  currency text not null default 'USD' check (currency = 'USD'),
  description text not null check (length(description) between 3 and 255),
  status text not null default 'open' check (status in ('open', 'paid', 'cancelled', 'failed')),
  created_by uuid references public.crm_users(user_id) on delete set null,
  created_by_name text not null,
  checkout_count integer not null default 0,
  last_checkout_at timestamptz,
  held_transaction_id text,
  failure_reason text,
  failed_at timestamptz,
  paid_at timestamptz,
  transaction_id text unique,
  transaction_status text,
  paid_amount_cents integer,
  card_brand text,
  card_last4 text check (card_last4 is null or card_last4 ~ '^[0-9]{4}$'),
  payer_email text,
  cancelled_at timestamptz,
  cancelled_by uuid references public.crm_users(user_id) on delete set null,
  email_send_count integer not null default 0,
  last_email_queued_at timestamptz,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  check (status <> 'paid' or (paid_at is not null and transaction_id is not null)),
  check (status = 'paid' or transaction_id is null),
  check (status <> 'cancelled' or cancelled_at is not null),
  check (status <> 'failed' or failure_reason is not null)
);
-- Target of the composite email-enrollment FK below.
create unique index payment_requests_id_contact_idx on public.payment_requests(id, contact_id);
create index payment_requests_contact_idx on public.payment_requests(contact_id, created_at desc);

create table public.payment_request_events (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.payment_requests(id) on delete cascade,
  actor_id uuid references public.crm_users(user_id) on delete set null,
  -- Staff display name | 'client' | 'system' | 'authorize.net'.
  actor_name text not null,
  action text not null check (action in (
    'created', 'link_emailed', 'checkout_started', 'checkout_failed', 'paid', 'failed', 'held',
    'voided', 'refunded', 'cancelled', 'duplicate_payment', 'paid_after_cancel', 'amount_mismatch', 'ignored'
  )),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default clock_timestamp()
);
create index payment_request_events_request_idx on public.payment_request_events(request_id, created_at desc, id desc);

-- Operational webhook log for idempotency. Excluded from CRM backups.
create table public.payment_webhook_events (
  notification_id text primary key check (length(notification_id) between 1 and 200),
  event_type text not null,
  transaction_id text,
  request_id uuid references public.payment_requests(id) on delete set null,
  outcome text not null default 'received' check (outcome in ('received', 'processed', 'ignored', 'retry')),
  payload jsonb not null default '{}'::jsonb,
  received_at timestamptz not null default clock_timestamp(),
  processed_at timestamptz
);

alter table public.payment_requests enable row level security;
alter table public.payment_request_events enable row level security;
alter table public.payment_webhook_events enable row level security;
revoke all on public.payment_requests, public.payment_request_events, public.payment_webhook_events
  from public, anon, authenticated;
grant all on public.payment_requests, public.payment_request_events, public.payment_webhook_events to service_role;
grant usage, select on sequence public.payment_request_events_id_seq to service_role;

create function public.guard_payment_request_contact_v1()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.contacts c where c.id = new.contact_id) then
    raise exception 'payment_request_contact_unavailable';
  end if;
  return new;
end;
$$;
