-- Unchanged from 20260912101000 apart from the added payment arm. Payment link
-- emails are transactional: universal suppression blocks them, marketing
-- consent and unsubscribe do not.
create or replace function public.email_message_is_eligible(p_contact_id uuid,p_enrollment_id uuid,p_template_key text)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select c.email_suppressed_at is null and e.status = 'active' and (
    (e.context_key = 'legacy'
      and (e.sequence_key = 'onboarding' or p_template_key = 'pre_webinar:1' or (c.marketing_consent and c.unsubscribed_at is null))
      and not (e.sequence_key <> 'onboarding' and exists (select 1 from public.events v where v.contact_id=c.id and v.event_key='call_booked'))
      and not (e.sequence_key='pre_webinar' and p_template_key <> 'pre_webinar:1' and exists (
        select 1 from public.events v where v.contact_id=c.id and coalesce(v.properties->>'funnel','') <> 'live'
        and v.event_key in ('webinar_room_opened','webinar_watch_25','webinar_watch_50','webinar_watch_75','webinar_watch_90','webinar_completed')
      )))
    or (e.live_registration_id is not null and exists (
      select 1 from public.live_webinar_registrations r join public.live_webinar_sessions s on s.id=r.session_id
      where r.id=e.live_registration_id and r.contact_id=c.id and r.cancelled_at is null
        and not r.notifications_paused and s.automation_enabled
        and ((p_template_key in ('live_confirmation:1','live_reminder_day:1','live_reminder_soon:1','live_rescheduled:1') and s.status='scheduled')
          or (p_template_key='live_cancelled:1' and s.status='cancelled')
          or (p_template_key in ('live_attended:1','live_no_show:1','live_replay:1') and s.status='scheduled'
            and c.marketing_consent and c.unsubscribed_at is null and c.stage not in ('won','lost','booked','call_booked')
            and not exists (select 1 from public.events v where v.contact_id=c.id and v.event_key='call_booked')))
    ))
    or (e.payment_request_id is not null and exists (
      select 1 from public.payment_requests p
      where p.id=e.payment_request_id and p.contact_id=c.id and p.status in ('open','failed')
    ))
  ) from public.contacts c join public.sequence_enrollments e on e.contact_id=c.id and e.id=p_enrollment_id
    where c.id=p_contact_id),false);
$$;

create or replace function public.email_message_is_eligible_v2(p_message_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select public.email_message_is_eligible(m.contact_id,m.enrollment_id,m.template_key)
    and (e.context_key='legacy'
    or (e.payment_request_id is not null and m.payload->>'paymentRequestId'=e.payment_request_id::text)
    or (
      m.payload->>'registrationId'=r.id::text and m.payload->>'sessionId'=s.id::text
      and m.payload->>'accessVersion'=r.access_version::text
      and m.payload->>'sessionVersion'=s.schedule_version::text
      and (nullif(m.payload->>'sendDeadline','') is null or (m.payload->>'sendDeadline')::timestamptz>now())
      and case m.template_key
        when 'live_confirmation:1' then now()<s.ends_at
        when 'live_reminder_day:1' then now()<s.starts_at-interval '15 minutes'
        when 'live_reminder_soon:1' then now()<s.starts_at
        when 'live_rescheduled:1' then now()<s.ends_at
        when 'live_cancelled:1' then s.status='cancelled'
        when 'live_attended:1' then now()>=s.ends_at+make_interval(mins=>s.attendance_grace_minutes) and r.attended_at is not null
        when 'live_no_show:1' then now()>=s.ends_at+make_interval(mins=>s.attendance_grace_minutes) and r.attended_at is null
        when 'live_replay:1' then s.replay_published and s.replay_url is not null and now()>=s.ends_at
          and (s.replay_available_until is null or s.replay_available_until>now())
        else false end
    ))
    from public.scheduled_messages m join public.sequence_enrollments e on e.id=m.enrollment_id
    left join public.live_webinar_registrations r on r.id=e.live_registration_id
    left join public.live_webinar_sessions s on s.id=r.session_id where m.id=p_message_id),false);
$$;

-- Payment link emails are claimed by the cron worker even while live webinar
-- delivery is disabled (the legacy predicate is extended to payment contexts).
create or replace function public.claim_due_scheduled_emails_v2(p_limit integer default 10,p_include_live boolean default false)
returns table(message_id uuid,email text,template_key text,payload jsonb)
language plpgsql security definer set search_path = '' as $$
begin
  if p_limit<1 or p_limit>100 then raise exception 'invalid_limit'; end if;
  update public.scheduled_messages set status='scheduled',updated_at=now()
    where status='sending' and updated_at<now()-interval '15 minutes'
      and (p_include_live or enrollment_id in (select id from public.sequence_enrollments where context_key='legacy' or payment_request_id is not null));
  update public.scheduled_messages m set status='cancelled',last_error='Cancelled at send time: no longer eligible',updated_at=now()
    where m.status='scheduled' and m.scheduled_for<=now() and not public.email_message_is_eligible_v2(m.id)
      and (p_include_live or m.enrollment_id in (select id from public.sequence_enrollments where context_key='legacy' or payment_request_id is not null))
      -- A disabled session is paused, not permanently consumed by an old worker.
      and not exists (select 1 from public.sequence_enrollments e join public.live_webinar_registrations r on r.id=e.live_registration_id
        join public.live_webinar_sessions s on s.id=r.session_id where e.id=m.enrollment_id and not s.automation_enabled);
  return query with due as (
    select m.id from public.scheduled_messages m where m.status='scheduled' and m.scheduled_for<=now()
      and (p_include_live or m.enrollment_id in (select id from public.sequence_enrollments where context_key='legacy' or payment_request_id is not null))
      and public.email_message_is_eligible_v2(m.id) order by m.scheduled_for,m.id for update of m skip locked limit p_limit
  ), claimed as (
    update public.scheduled_messages m set status='sending',attempts=m.attempts+1,last_error=null,updated_at=now()
      from due where m.id=due.id returning m.id,m.contact_id,m.template_key,m.payload
  ) select m.id,c.email::text,m.template_key,m.payload from claimed m join public.contacts c on c.id=m.contact_id;
end; $$;

-- Signature unchanged; adds the 'payment' bucket for the public pay routes.
create or replace function public.consume_rate_limit(
  p_bucket text,
  p_key_hash text,
  p_window_seconds integer,
  p_limit integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_window timestamptz;
  current_count integer;
begin
  if p_bucket not in ('registration', 'booking', 'tracking', 'live-question', 'live-activity', 'payment') then raise exception 'invalid_bucket'; end if;
  if p_key_hash !~ '^[0-9a-f]{64}$' then raise exception 'invalid_key_hash'; end if;
  if p_window_seconds < 10 or p_window_seconds > 3600 then raise exception 'invalid_window'; end if;
  if p_limit < 1 or p_limit > 1000 then raise exception 'invalid_limit'; end if;

  current_window := to_timestamp(floor(extract(epoch from clock_timestamp()) / p_window_seconds) * p_window_seconds);

  delete from public.rate_limit_counters
  where bucket = p_bucket and key_hash = p_key_hash
    and window_start < current_window - interval '1 hour';

  insert into public.rate_limit_counters (bucket, key_hash, window_start, request_count)
  values (p_bucket, p_key_hash, current_window, 1)
  on conflict (bucket, key_hash, window_start) do update
  set request_count = public.rate_limit_counters.request_count + 1
  returning request_count into current_count;

  return current_count <= p_limit;
end;
$$;

-- One CRM list item. Used by create and list so both return the same shape.
create function public.payment_request_item_v1(p_request_id uuid)
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'id', p.id, 'reference', p.reference, 'linkToken', p.link_token,
    'amountCents', p.amount_cents, 'currency', p.currency, 'description', p.description,
    'status', p.status, 'createdAt', p.created_at, 'createdByName', p.created_by_name,
    'paidAt', p.paid_at, 'transactionId', p.transaction_id, 'transactionStatus', p.transaction_status,
    'paidAmountCents', p.paid_amount_cents, 'cardBrand', p.card_brand, 'cardLast4', p.card_last4,
    'payerEmail', p.payer_email, 'failureReason', p.failure_reason, 'failedAt', p.failed_at,
    'heldTransactionId', p.held_transaction_id, 'cancelledAt', p.cancelled_at,
    'checkoutCount', p.checkout_count, 'lastCheckoutAt', p.last_checkout_at,
    'emailSendCount', p.email_send_count, 'lastEmailQueuedAt', p.last_email_queued_at,
    'lastEmail', (
      select jsonb_build_object('status', m.status, 'scheduledFor', m.scheduled_for, 'sentAt', m.sent_at, 'lastError', m.last_error)
      from public.scheduled_messages m join public.sequence_enrollments e on e.id = m.enrollment_id
      where e.payment_request_id = p.id
      order by m.created_at desc, m.id desc limit 1
    ),
    'events', coalesce((
      select jsonb_agg(jsonb_build_object('action', x.action, 'actorName', x.actor_name, 'createdAt', x.created_at, 'details', x.details)
        order by x.created_at desc, x.id desc)
      from (select ev.* from public.payment_request_events ev where ev.request_id = p.id
        order by ev.created_at desc, ev.id desc limit 20) x
    ), '[]'::jsonb)
  ) from public.payment_requests p where p.id = p_request_id;
$$;

create function public.create_payment_request_v1(
  p_contact_id uuid, p_amount_cents integer, p_description text, p_actor_id uuid, p_reference text, p_link_token text
)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare actor_name text; contact_row public.contacts%rowtype; clean_description text := trim(coalesce(p_description, '')); new_id uuid;
begin
  select display_name into actor_name from public.crm_users where user_id = p_actor_id and role in ('admin', 'staff');
  if not found then raise exception 'payment_request_actor_invalid'; end if;
  select * into contact_row from public.contacts where id = p_contact_id;
  if not found then raise exception 'payment_request_contact_unavailable'; end if;
  if p_amount_cents is null or p_amount_cents < 100 or p_amount_cents > 2500000 then
    raise exception 'payment_request_amount_invalid';
  end if;
  if length(clean_description) < 3 or length(clean_description) > 255 or clean_description ~ '[[:cntrl:]]' then
    raise exception 'payment_request_description_invalid';
  end if;
  insert into public.payment_requests(contact_id, reference, link_token, amount_cents, description, created_by, created_by_name)
  values (p_contact_id, p_reference, p_link_token, p_amount_cents, clean_description, p_actor_id, coalesce(actor_name, 'CRM user'))
  returning id into new_id;
  insert into public.payment_request_events(request_id, actor_id, actor_name, action, details)
  values (new_id, p_actor_id, coalesce(actor_name, 'CRM user'), 'created',
    jsonb_build_object('amountCents', p_amount_cents, 'reference', p_reference));
  insert into public.events(event_key, contact_id, email, properties)
  values ('payment_request_created', contact_row.id, contact_row.email, jsonb_build_object(
    'amountCents', p_amount_cents, 'reference', p_reference, 'description', clean_description));
  return public.payment_request_item_v1(new_id);
end;
$$;

create function public.list_payment_requests_v1(p_contact_id uuid)
returns jsonb language sql stable security definer set search_path = '' as $$
  select case when not exists (select 1 from public.contacts c where c.id = p_contact_id) then '[]'::jsonb
  else coalesce((
    select jsonb_agg(public.payment_request_item_v1(q.id) order by q.created_at desc, q.id desc)
    from (select p.id, p.created_at from public.payment_requests p where p.contact_id = p_contact_id
      order by p.created_at desc, p.id desc limit 200) q
  ), '[]'::jsonb) end;
$$;

