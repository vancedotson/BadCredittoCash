-- Existing full sets predate atomic capture. One current latest receipt is the
-- only qualifying event recoverable because the old schema replaced each
-- bureau row in place and did not preserve its earlier receipt history.
do $$
declare latest_receipt uuid;
begin
  for latest_receipt in
    with full_contacts as (
      select contact_id from public.credit_report_uploads group by contact_id having count(distinct bureau) = 3
    )
    select distinct on (u.contact_id) u.id from public.credit_report_uploads u
      join full_contacts f on f.contact_id = u.contact_id
      order by u.contact_id, u.uploaded_at desc, u.id desc
  loop
    perform public.ensure_credit_report_followup_for_receipt_v1(latest_receipt);
  end loop;
end;
$$;

