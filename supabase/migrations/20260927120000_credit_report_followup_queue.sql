create function public.export_crm_contact_v1(p_contact_id uuid)
returns jsonb language sql stable security definer set search_path = '' as $$
  with base as materialized (select public.export_crm_contact_pre_followup_v1(p_contact_id) as payload)
  select case when base.payload is null then null else base.payload || jsonb_build_object(
    'version', 3,
    'creditReportFollowupObligations', coalesce((select jsonb_agg(
      to_jsonb(o) || jsonb_build_object('assigned_to', null, 'completed_by', null)
      order by o.created_at, o.id)
      from public.credit_report_followup_obligations o where o.contact_id=p_contact_id), '[]'::jsonb),
    'creditReportFollowupReceipts', coalesce((select jsonb_agg(to_jsonb(r) order by r.uploaded_at, r.receipt_id)
      from public.credit_report_followup_receipts r where r.contact_id=p_contact_id), '[]'::jsonb),
    'creditReportFollowupContactAttempts', coalesce((select jsonb_agg(
      to_jsonb(a) || jsonb_build_object('actor_id', null) order by a.contacted_at, a.id)
      from public.credit_report_followup_contact_attempts a
      join public.credit_report_followup_obligations o on o.id=a.obligation_id
      where o.contact_id=p_contact_id), '[]'::jsonb),
    'creditReportFollowupAudit', coalesce((select jsonb_agg(
      to_jsonb(a) || jsonb_build_object(
        'actor_id', null,
        'before_state', case when a.before_state is null then null else a.before_state - 'assignedTo' end,
        'after_state', case when a.after_state is null then null else a.after_state - 'assignedTo' end
      ) order by a.created_at, a.id)
      from public.credit_report_followup_audit a
      join public.credit_report_followup_obligations o on o.id=a.obligation_id
      where o.contact_id=p_contact_id), '[]'::jsonb)
  ) end from base;
$$;
