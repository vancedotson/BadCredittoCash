  perform public.ensure_credit_report_followup_for_receipt_v1(new.id);
  return new;
end;
$$;
create trigger credit_report_followup_receipt_capture
  after insert or update on public.credit_report_uploads
  for each row execute function public.capture_credit_report_followup_receipt_v1();

create function public.reconcile_credit_report_followup_receipts_v1(p_limit integer default 100)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare candidate record; scanned integer := 0; created integer := 0; has_more boolean := false;
begin
  if p_limit < 1 or p_limit > 500 then raise exception 'credit_report_followup_limit_invalid'; end if;
  for candidate in
    with full_contacts as (
      select u.contact_id from public.credit_report_uploads u
      group by u.contact_id having count(distinct u.bureau) = 3
    ), latest as (
      select distinct on (u.contact_id) u.id, u.contact_id
      from public.credit_report_uploads u join full_contacts f on f.contact_id = u.contact_id
      order by u.contact_id, u.uploaded_at desc, u.id desc
    )
    select l.id as receipt_id from latest l
    where not exists (select 1 from public.credit_report_followup_receipts r where r.receipt_id = l.id)
    order by l.id limit p_limit + 1
  loop
    if scanned >= p_limit then has_more := true; exit; end if;
    scanned := scanned + 1;
    if public.ensure_credit_report_followup_for_receipt_v1(candidate.receipt_id) is not null then created := created + 1; end if;
  end loop;
  return jsonb_build_object('scanned', scanned, 'reconciled', created, 'hasMore', has_more);
end;
$$;

create or replace function public.finish_credit_report_attempt_reconciliation_v1(
  p_attempt_id uuid, p_claim_token uuid, p_object_exists boolean, p_object_removed boolean default false
)
returns text language plpgsql security definer set search_path = '' as $$
declare attempt_row public.credit_report_upload_attempts%rowtype; has_receipt boolean;
begin
  select * into attempt_row from public.credit_report_upload_attempts where id = p_attempt_id;
  if not found then raise exception 'credit_report_attempt_missing'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(attempt_row.contact_id::text, 9142));
  select * into attempt_row from public.credit_report_upload_attempts where id = p_attempt_id for update;
  if attempt_row.reconciliation_token is distinct from p_claim_token then raise exception 'credit_report_claim_lost'; end if;
  select exists (select 1 from public.credit_report_uploads u where u.id = attempt_row.id and u.contact_id = attempt_row.contact_id and u.object_path = attempt_row.object_path)
    into has_receipt;
  if p_object_exists and has_receipt then
    if not exists (select 1 from storage.objects where bucket_id = 'credit-reports' and name = attempt_row.object_path) then
      raise exception 'credit_report_object_not_confirmed';
    end if;
    perform public.ensure_credit_report_followup_for_receipt_v1(attempt_row.id);
    update public.credit_report_upload_attempts set state = 'completed', completed_at = coalesce(completed_at, now()),
      upload_lease_until = null, reconciliation_token = null, reconciliation_lease_until = null,
      next_reconcile_at = now() + interval '24 hours', last_failure_code = null where id = p_attempt_id;
    return 'completed';
  end if;
  if p_object_exists and not p_object_removed then raise exception 'credit_report_object_removal_unconfirmed'; end if;
  if exists (select 1 from storage.objects where bucket_id = 'credit-reports' and name = attempt_row.object_path) then
    raise exception 'credit_report_object_still_exists';
  end if;
  delete from public.credit_report_uploads u where u.id = attempt_row.id and u.contact_id = attempt_row.contact_id and u.object_path = attempt_row.object_path;
  update public.credit_report_upload_attempts set state = 'abandoned', completed_at = null,
    upload_lease_until = null, reconciliation_token = null, reconciliation_lease_until = null,
    next_reconcile_at = now() + interval '1 hour', last_failure_code = null where id = p_attempt_id;
  return 'abandoned';
end;
$$;

create function public.list_credit_report_followups_v1()
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('items', coalesce(jsonb_agg(item order by state_sort, due_at, created_at), '[]'::jsonb))
  from (
    select jsonb_build_object(
      'id', o.id, 'contactId', o.contact_id, 'contactName', c.name, 'contactEmail', c.email,
      'state', o.state, 'dueAt', o.due_at, 'assignedTo', o.assigned_to,
      'assignedName', assigned.display_name, 'createdAt', o.created_at, 'completedAt', o.completed_at,
      'receipts', coalesce((select jsonb_agg(jsonb_build_object(
        'bureau', r.bureau, 'uploadedAt', r.uploaded_at, 'dueAt', r.due_at
      ) order by r.uploaded_at, r.receipt_id) from public.credit_report_followup_receipts r where r.obligation_id = o.id), '[]'::jsonb),
      'attempts', coalesce((select jsonb_agg(jsonb_build_object(
        'actorName', a.actor_name, 'contactedAt', a.contacted_at, 'channel', a.channel,
        'outcome', a.outcome, 'recordedAt', a.recorded_at
      ) order by a.contacted_at desc, a.id desc) from public.credit_report_followup_contact_attempts a where a.obligation_id = o.id), '[]'::jsonb)
    ) as item, o.state,
    case when o.state = 'open' then 0 else 1 end as state_sort, o.due_at, o.created_at
    from public.credit_report_followup_obligations o
    join public.contacts c on c.id = o.contact_id
    left join public.crm_users assigned on assigned.user_id = o.assigned_to
    order by state_sort, o.due_at, o.created_at
    limit 500
  ) q;
$$;

