create or replace function public.purge_crm_contact_v1(p_contact_id uuid)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_contact_id::text, 9142));
  if not exists (select 1 from public.credit_report_purge_blocks where contact_id = p_contact_id) then
    raise exception 'credit_report_purge_not_prepared';
  end if;
  if exists (select 1 from public.credit_report_upload_attempts where contact_id = p_contact_id and state = 'pending') then
    raise exception 'credit_report_upload_still_pending';
  end if;
  if exists (select 1 from storage.objects where bucket_id = 'credit-reports' and name like p_contact_id::text || '/%') then
    raise exception 'credit_report_files_not_deleted';
  end if;
  -- Recoverable trash retains queue metadata because it retains report metadata.
  -- Permanent erasure explicitly deletes it before the base contact is removed.
  delete from public.credit_report_followup_obligations where contact_id = p_contact_id;
  delete from public.credit_report_uploads where contact_id = p_contact_id;
  delete from public.credit_report_upload_sessions where contact_id = p_contact_id;
  delete from public.credit_report_upload_attempts where contact_id = p_contact_id and state = 'completed';
  delete from public.credit_report_obsolete_objects where contact_id = p_contact_id;
  perform public.purge_crm_contact_records_v1(p_contact_id);
  return true;
end;
$$;

create or replace function public.restore_crm_backup_v1(p_backup jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare table_data jsonb := p_backup->'tables'; restored_contacts integer;
begin
  if coalesce(p_backup->>'format', '') <> 'vance-crm-backup' or coalesce((p_backup->>'version')::integer, 0) not in (1,2,3) then raise exception 'unsupported_backup_format'; end if;
  if jsonb_typeof(table_data) <> 'object' then raise exception 'missing_backup_tables'; end if;
  delete from public.scheduled_messages where id is not null;
  delete from public.sequence_enrollments where id is not null;
  delete from public.bookings where id is not null;
  delete from public.notes where id is not null;
  delete from public.tasks where id is not null;
  delete from public.contact_tags where contact_id is not null;
  delete from public.tags where id is not null;
  delete from public.events where id is not null;
  delete from public.live_webinar_registrations where id is not null;
  delete from public.credit_report_followup_audit where id is not null;
  delete from public.credit_report_followup_contact_attempts where id is not null;
  delete from public.credit_report_followup_receipts where receipt_id is not null;
  delete from public.credit_report_followup_obligations where id is not null;
  delete from public.contacts where id is not null;
  delete from public.live_webinar_sessions where id is not null;
  delete from public.settings where key is not null;

  insert into public.contacts select * from jsonb_populate_recordset(null::public.contacts, public.upgrade_live_crm_rows_v1('contacts',table_data->'contacts'));
  get diagnostics restored_contacts = row_count;
  insert into public.events select * from jsonb_populate_recordset(null::public.events, coalesce(table_data->'events', '[]'::jsonb));
  insert into public.notes select * from jsonb_populate_recordset(null::public.notes, coalesce(table_data->'notes', '[]'::jsonb));
