create function public.ensure_credit_report_followup_for_receipt_v1(p_receipt_id uuid)
returns uuid language plpgsql security definer set search_path = '' as $$
declare
  receipt_row public.credit_report_uploads%rowtype;
  obligation_id uuid;
  default_assignee uuid;
  event_due_at timestamptz;
begin
  select * into receipt_row from public.credit_report_uploads where id = p_receipt_id;
  if not found then return null; end if;
  if not exists (select 1 from public.contacts where id = receipt_row.contact_id) then return null; end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(receipt_row.contact_id::text, 9142));
  if (select count(distinct u.bureau) from public.credit_report_uploads u where u.contact_id = receipt_row.contact_id) < 3 then
    return null;
  end if;

  select r.obligation_id into obligation_id
  from public.credit_report_followup_receipts r where r.receipt_id = p_receipt_id;
  if obligation_id is not null then return obligation_id; end if;

  event_due_at := receipt_row.uploaded_at + interval '48 hours';
  select o.id into obligation_id
  from public.credit_report_followup_obligations o
  where o.contact_id = receipt_row.contact_id and o.state = 'open'
  for update;

  if obligation_id is null then
    select c.owner_id into default_assignee
    from public.contacts c join public.crm_users u on u.user_id = c.owner_id
    where c.id = receipt_row.contact_id and u.role <> 'readonly';
    if default_assignee is null then
      select u.user_id into default_assignee from public.crm_users u
      where u.role = 'admin' order by u.created_at, u.user_id limit 1;
    end if;
    insert into public.credit_report_followup_obligations(contact_id, due_at, assigned_to)
    values (receipt_row.contact_id, event_due_at, default_assignee)
    returning id into obligation_id;
    insert into public.credit_report_followup_audit(obligation_id, actor_name, action, after_state)
    values (obligation_id, 'system', 'assigned', jsonb_build_object('assignedTo', default_assignee, 'source', 'automatic'));
  else
    update public.credit_report_followup_obligations
      set due_at = least(due_at, event_due_at), updated_at = pg_catalog.clock_timestamp()
      where id = obligation_id;
  end if;

  insert into public.credit_report_followup_receipts(receipt_id, obligation_id, contact_id, bureau, uploaded_at, due_at)
  values (p_receipt_id, obligation_id, receipt_row.contact_id, receipt_row.bureau, receipt_row.uploaded_at, event_due_at)
  on conflict (receipt_id) do nothing;
  return obligation_id;
end;
$$;

create function public.capture_credit_report_followup_receipt_v1()
returns trigger language plpgsql security definer set search_path = '' as $$
