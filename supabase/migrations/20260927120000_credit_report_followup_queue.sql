-- Private, upload-driven 48-hour follow-up queue. This migration is additive;
-- it does not alter the public credit-check page or send customer messages.

create table public.credit_report_followup_obligations (
  id uuid primary key default gen_random_uuid(),
  -- No contacts FK: the existing recoverable-trash flow temporarily removes
  -- the active contact row while preserving private report metadata.
  contact_id uuid not null,
  due_at timestamptz not null,
  assigned_to uuid references public.crm_users(user_id) on delete set null,
  state text not null default 'open' check (state in ('open', 'completed')),
  completed_at timestamptz,
  completed_by uuid references public.crm_users(user_id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  check ((state = 'open' and completed_at is null) or (state = 'completed' and completed_at is not null))
);
create unique index credit_report_followup_one_open_per_contact_idx
  on public.credit_report_followup_obligations(contact_id) where state = 'open';
create index credit_report_followup_due_idx
  on public.credit_report_followup_obligations(state, due_at, created_at);

-- Receipt IDs are retained as opaque UUIDs without a foreign key so replacing
-- a PDF does not erase the qualifying-receipt trace. No object path or bytes are
-- stored here. Contact trash retains this metadata; permanent purge deletes the
-- obligation and cascades these traces.
create table public.credit_report_followup_receipts (
  receipt_id uuid primary key,
  obligation_id uuid not null references public.credit_report_followup_obligations(id) on delete cascade,
  contact_id uuid not null,
  bureau text not null check (bureau in ('transunion', 'equifax', 'experian')),
  uploaded_at timestamptz not null,
  due_at timestamptz not null,
  recorded_at timestamptz not null default clock_timestamp()
);
create index credit_report_followup_receipts_obligation_idx
  on public.credit_report_followup_receipts(obligation_id, uploaded_at, receipt_id);

create table public.credit_report_followup_contact_attempts (
  id uuid primary key default gen_random_uuid(),
  obligation_id uuid not null references public.credit_report_followup_obligations(id) on delete cascade,
  actor_id uuid references public.crm_users(user_id) on delete set null,
  actor_name text not null,
  contacted_at timestamptz not null,
  channel text not null check (channel in ('phone', 'email', 'other')),
  outcome text not null check (outcome in ('reached', 'no_answer', 'left_message', 'other')),
  recorded_at timestamptz not null default clock_timestamp(),
  check (contacted_at <= recorded_at + interval '5 minutes')
);
create index credit_report_followup_attempts_obligation_idx
  on public.credit_report_followup_contact_attempts(obligation_id, contacted_at desc);

create table public.credit_report_followup_audit (
  id bigint generated by default as identity primary key,
  obligation_id uuid not null references public.credit_report_followup_obligations(id) on delete cascade,
  actor_id uuid references public.crm_users(user_id) on delete set null,
  actor_name text not null,
  action text not null check (action in ('assigned', 'contact_recorded')),
  before_state jsonb,
  after_state jsonb not null,
  created_at timestamptz not null default clock_timestamp()
);
create index credit_report_followup_audit_obligation_idx
  on public.credit_report_followup_audit(obligation_id, created_at desc);

alter table public.credit_report_followup_obligations enable row level security;
alter table public.credit_report_followup_receipts enable row level security;
alter table public.credit_report_followup_contact_attempts enable row level security;
alter table public.credit_report_followup_audit enable row level security;
revoke all on public.credit_report_followup_obligations, public.credit_report_followup_receipts,
  public.credit_report_followup_contact_attempts, public.credit_report_followup_audit
  from public, anon, authenticated;
grant all on public.credit_report_followup_obligations, public.credit_report_followup_receipts,
  public.credit_report_followup_contact_attempts, public.credit_report_followup_audit to service_role;
grant usage, select on sequence public.credit_report_followup_audit_id_seq to service_role;

