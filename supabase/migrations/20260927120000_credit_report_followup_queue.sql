create function public.assign_credit_report_followup_v1(p_obligation_id uuid, p_assignee_id uuid, p_actor_id uuid)
returns boolean language plpgsql security definer set search_path = '' as $$
declare before_assignee uuid; actor_name text; assignee_role public.crm_role;
begin
  select display_name into actor_name from public.crm_users where user_id = p_actor_id and role in ('admin', 'staff');
  if not found then raise exception 'credit_report_followup_actor_invalid'; end if;
  if p_assignee_id is not null then
    select role into assignee_role from public.crm_users where user_id = p_assignee_id;
    if not found or assignee_role not in ('admin', 'staff') then raise exception 'credit_report_followup_assignee_invalid'; end if;
  end if;
  select assigned_to into before_assignee from public.credit_report_followup_obligations
    where id = p_obligation_id and state = 'open' for update;
  if not found then raise exception 'credit_report_followup_missing'; end if;
  if before_assignee is not distinct from p_assignee_id then return true; end if;
  update public.credit_report_followup_obligations set assigned_to = p_assignee_id, updated_at = pg_catalog.clock_timestamp()
    where id = p_obligation_id;
  insert into public.credit_report_followup_audit(obligation_id, actor_id, actor_name, action, before_state, after_state)
  values (p_obligation_id, p_actor_id, coalesce(actor_name, 'CRM user'), 'assigned',
    jsonb_build_object('assignedTo', before_assignee), jsonb_build_object('assignedTo', p_assignee_id));
  return true;
end;
$$;

create function public.record_credit_report_followup_contact_v1(
  p_obligation_id uuid, p_actor_id uuid, p_contacted_at timestamptz, p_channel text, p_outcome text
)
returns uuid language plpgsql security definer set search_path = '' as $$
declare actor_name text; attempt_id uuid := gen_random_uuid(); previous_state text; obligation_created_at timestamptz;
begin
  if p_channel not in ('phone', 'email', 'other') or p_outcome not in ('reached', 'no_answer', 'left_message', 'other') then
    raise exception 'credit_report_followup_outcome_invalid';
  end if;
  if p_contacted_at is null or p_contacted_at > pg_catalog.clock_timestamp() + interval '5 minutes' then
    raise exception 'credit_report_followup_time_invalid';
  end if;
  select display_name into actor_name from public.crm_users where user_id = p_actor_id and role in ('admin', 'staff');
  if not found then raise exception 'credit_report_followup_actor_invalid'; end if;
  select state, created_at into previous_state, obligation_created_at from public.credit_report_followup_obligations
    where id = p_obligation_id and state = 'open' for update;
  if not found then raise exception 'credit_report_followup_missing'; end if;
  if p_contacted_at < obligation_created_at then raise exception 'credit_report_followup_time_invalid'; end if;
  insert into public.credit_report_followup_contact_attempts(id, obligation_id, actor_id, actor_name, contacted_at, channel, outcome)
  values (attempt_id, p_obligation_id, p_actor_id, coalesce(actor_name, 'CRM user'), p_contacted_at, p_channel, p_outcome);
  if p_outcome = 'reached' then
    update public.credit_report_followup_obligations set state = 'completed', completed_at = p_contacted_at,
      completed_by = p_actor_id, updated_at = pg_catalog.clock_timestamp() where id = p_obligation_id;
  else
    update public.credit_report_followup_obligations set updated_at = pg_catalog.clock_timestamp() where id = p_obligation_id;
  end if;
  insert into public.credit_report_followup_audit(obligation_id, actor_id, actor_name, action, before_state, after_state)
  values (p_obligation_id, p_actor_id, coalesce(actor_name, 'CRM user'), 'contact_recorded',
    jsonb_build_object('state', previous_state), jsonb_build_object(
      'attemptId', attempt_id, 'contactedAt', p_contacted_at, 'channel', p_channel,
      'outcome', p_outcome, 'state', case when p_outcome = 'reached' then 'completed' else 'open' end
    ));
  return attempt_id;
end;
$$;

